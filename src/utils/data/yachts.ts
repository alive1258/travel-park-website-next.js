interface YachtInput {
  slug: string;
  name: string;
  tagline: string;
  category: string;
  lengthFt: number;
  lengthM: number;
  builtYear: number;
  refitYear: number;
  guests: number;
  cabins: number;
  crew: number;
  priceNight: number;
  region: string;
  cruisingSpeed: number;
  maxSpeed: number;
  range: number;
  engines: string;
  hullMaterial: string;
  builder: string;
  heroImage: string;
  gallery: string[];
  description: string[];
  specialFeatures: string[];
}

const usd = (value: number) => `$${value.toLocaleString("en-US")}`;

/** Builds a fully specified Yacht record from a compact input, deriving the
 * repetitive display/spec fields so each fleet entry only has to declare
 * what actually makes it different. */
function buildYacht(input: YachtInput): Yacht {
  const doubles = Math.ceil(input.cabins * 0.5);
  const twins = Math.floor(input.cabins * 0.35);
  const convertible = Math.max(input.cabins - doubles - twins, 0);

  return {
    id: input.slug,
    slug: input.slug,
    name: input.name,
    tagline: input.tagline,
    category: input.category,
    length: `${input.lengthFt} ft / ${input.lengthM}m`,
    builtRefit: `${input.builtYear}/${input.refitYear}`,
    guests: input.guests,
    cabins: input.cabins,
    crew: input.crew,
    priceFrom: usd(input.priceNight),
    priceUnit: "per night",
    pricePerNight: input.priceNight,
    currency: "USD",
    heroImage: input.heroImage,
    gallery: input.gallery,
    description: input.description,
    specialFeatures: input.specialFeatures,
    specifications: {
      accommodation: {
        guestsCruising: Math.round(input.guests * 1.6),
        guestsSleeping: input.guests,
        staterooms: input.cabins,
        cabinConfig: [
          { type: "Double", count: doubles },
          { type: "Twin", count: twins },
          { type: "Convertible", count: convertible },
        ].filter((c) => c.count > 0),
        crew: input.crew,
      },
      construction: {
        builtYear: input.builtYear,
        refitYear: input.refitYear,
        builder: input.builder,
        hullMaterial: input.hullMaterial,
        exteriorDesigner: "Eco Yachts Design Studio",
        interiorDesigner: "Eco Yachts Design Studio",
      },
      dimensions: {
        length: `${input.lengthM}m (${input.lengthFt}')`,
        beam: `${(input.lengthM * 0.16).toFixed(2)}m`,
        draft: `${(input.lengthM * 0.06).toFixed(2)}m`,
        grossTonnage: `${Math.round(input.lengthM * input.lengthM * 0.9)} GT`,
      },
      performance: {
        cruisingSpeed: `${input.cruisingSpeed} Knots`,
        maxSpeed: `${input.maxSpeed} Knots`,
        range: `${input.range.toLocaleString("en-US")} nm`,
        engines: input.engines,
        generators: "2 x Hybrid-Ready Marine Generators",
      },
      classification: {
        classification: "Lloyd's Register / Green Passport",
        flag: "Malta",
      },
      amenities: [
        "WiFi",
        "Air Conditioning",
        "Water Toys",
        "Eco-Certified Waste Systems",
      ],
    },
    rates: [
      {
        season: "Summer",
        dateRange: "May – September",
        region: input.region,
        lowSeason: `${usd(input.priceNight)} p/night`,
        highSeason: `${usd(Math.round(input.priceNight * 1.18))} p/night`,
      },
      {
        season: "Winter",
        dateRange: "October – April",
        region: "Caribbean & Bahamas",
        lowSeason: `${usd(Math.round(input.priceNight * 0.9))} p/night`,
        highSeason: `${usd(Math.round(input.priceNight * 1.05))} p/night`,
      },
    ],
  };
}

